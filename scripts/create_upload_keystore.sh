#!/usr/bin/env bash
# Create the Android upload keystore and android/key.properties.
#
# The upload key signs the AAB you send to Google Play (Play App Signing then
# re-signs it with the app signing key). Upload the same .jks to Codemagic with
# reference name "upload_keystore". Lose it and you must request an upload key
# reset from Google - back it up somewhere safe (password manager / vault).
set -euo pipefail

# shellcheck source=scripts/_common.sh
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

usage() {
  cat <<EOF
Usage: $(basename "$0") [options]

Options:
  -o, --out <path>     Keystore path (default: android/upload-keystore.jks, gitignored).
                       Prefer a path outside the repo, e.g. ~/keystores/<app>-upload.jks.
  --alias <alias>      Key alias (default: upload).
  --dname <dname>      Certificate subject (default: "CN=<pubspec name>").
  -f, --force          Overwrite an existing android/key.properties.
  -h, --help           Show this help.

The password is read from \$KEYSTORE_PASSWORD if set, otherwise a random one is
generated and printed once. Store and key password are the same (PKCS12).
EOF
}

root=$(project_root)
keystore="$root/android/upload-keystore.jks"
alias_name=upload
dname=''
force=0
while (($#)); do
  case $1 in
    -h | --help) usage; exit 0 ;;
    -o | --out) keystore=${2:?--out needs a value}; shift ;;
    --alias) alias_name=${2:?--alias needs a value}; shift ;;
    --dname) dname=${2:?--dname needs a value}; shift ;;
    -f | --force) force=1 ;;
    *) usage >&2; die "unknown argument: $1" ;;
  esac
  shift
done

require_cmd keytool "Install a JDK (e.g. sudo apt install openjdk-17-jdk-headless) or use Android Studio's bundled JBR."

# Make the keystore path absolute.
# shellcheck disable=SC2088 # matching a literal "~/" the shell did not expand
case $keystore in
  "~/"*) keystore="$HOME/${keystore#\~/}" ;;
  /*) ;;
  *) keystore="$PWD/$keystore" ;;
esac
props="$root/android/key.properties"

[[ ! -e $keystore ]] || die "$keystore already exists; refusing to overwrite a signing key."
[[ ! -e $props || $force -eq 1 ]] || die "$props already exists (use --force to overwrite)."

[[ -n $dname ]] || dname="CN=$(read_pubspec_name "$root")"

if [[ -n ${KEYSTORE_PASSWORD:-} ]]; then
  generated=0
else
  # 32 alphanumerics: nothing that needs escaping in .properties files.
  KEYSTORE_PASSWORD=$(
    set +o pipefail # tr gets SIGPIPE when head exits
    LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 32
  )
  generated=1
fi
((${#KEYSTORE_PASSWORD} >= 6)) || die "KEYSTORE_PASSWORD must be at least 6 characters."
export KEYSTORE_PASSWORD

mkdir -p "$(dirname "$keystore")"
info "Generating $keystore"
keytool -genkeypair -v \
  -keystore "$keystore" -storetype PKCS12 \
  -alias "$alias_name" -keyalg RSA -keysize 2048 -validity 10000 \
  -dname "$dname" \
  -storepass:env KEYSTORE_PASSWORD -keypass:env KEYSTORE_PASSWORD >/dev/null 2>&1 ||
  die "keytool failed"
chmod 600 "$keystore"

# storeFile is resolved relative to android/app by Gradle (file(...) in the app module).
android_app_dir="$root/android/app"
case $keystore in
  "$root/android/"*) store_file="../${keystore#"$root/android/"}" ;;
  *) store_file=$keystore ;;
esac

umask 077
cat >"$props" <<EOF
# Release signing for local builds. Never commit this file.
# Generated by scripts/create_upload_keystore.sh. Paths are relative to android/app.
storePassword=$KEYSTORE_PASSWORD
keyPassword=$KEYSTORE_PASSWORD
keyAlias=$alias_name
storeFile=$store_file
EOF
ok "Wrote android/key.properties (storeFile=$store_file)"
[[ -f "$android_app_dir/$store_file" || -f $store_file ]] || warn "storeFile does not resolve from android/app - check the path."

if git -C "$root" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  for f in "$props" "$keystore"; do
    case $f in "$root"/*)
      git -C "$root" check-ignore -q "$f" || warn "${f#"$root"/} is NOT gitignored - add it to .gitignore before committing." ;;
    esac
  done
fi

echo
info "Fingerprints (add SHA-1 and SHA-256 to the Firebase Android app)"
keytool -list -v -keystore "$keystore" -alias "$alias_name" -storepass:env KEYSTORE_PASSWORD 2>/dev/null |
  sed -n -E 's/^[[:space:]]*(SHA1|SHA256):[[:space:]]*/    \1  /p'

if ((generated)); then
  cat <<EOF

${_c_yellow}${_c_bold}Keystore password (shown once - save it in your password manager):${_c_reset}
    $KEYSTORE_PASSWORD
EOF
fi

cat <<EOF

Next steps:
  1. Back up $keystore and its password (losing it means an upload-key reset with Google).
  2. Codemagic > Settings (personal) / Team settings (team) > codemagic.yaml settings > Code signing identities >
     Android keystores: upload the .jks with
       reference name: upload_keystore   key alias: $alias_name   (passwords as above)
  3. Add the SHA-1/SHA-256 above to Firebase (or re-run scripts/configure_firebase.sh <project-id>,
     which registers them automatically).
  4. After the first Play upload, also add the Play App Signing key fingerprints
     (Play Console > Test and release > App integrity).
EOF
